"""AD-1195: which EventType members events.db can answer for.

A stdlib-only leaf keyed by member NAME, so ``EventType``, its values, ``str``
equality and pickling stay untouched. It must not import ``probos.events``:
``probos.events`` calls ``assert_complete`` with its member names right after
the class, so the import fails while a member is neither declared nor in the
``GRANDFATHERED`` snapshot.

A DURABLE member is recorded one of two ways. ``DurableEventRouter`` writes it
as a ``(ROUTED_CATEGORY, <value>)`` row, or an existing OWNER already writes
its own row (``OWNER_RECORDS``). The router skips owner members, so those rows
are never doubled.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from enum import Enum
from types import MappingProxyType
from typing import Final


class Persistence(str, Enum):
    """How far events.db can answer for an EventType member."""

    DURABLE = "durable"
    """Persisted: absence within retention is evidence."""
    OPERATIONAL = "operational"
    """Live dispatch only: never persisted by the router."""
    DIAGNOSTIC = "diagnostic"
    """Best effort: absence is never evidence."""


class EventPersistenceContractError(RuntimeError):
    """The EventType members and these tables disagree; raised when ``probos.events`` imports."""


