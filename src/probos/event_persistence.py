def persistence_of(name: str) -> Persistence | None:
    """The declared class of member ``name``, or None when it is not declared."""
    return DECLARATIONS.get(name)


def is_routed(name: str) -> bool:
    """True when the router writes member ``name``: DURABLE and not owner-written."""
    return DECLARATIONS.get(name) is Persistence.DURABLE and name not in OWNER_RECORDS


def durable_record_key(name: str, value: str) -> tuple[str, str] | None:
    """The ``(category, event)`` row that records DURABLE member ``name``, else None."""
    if DECLARATIONS.get(name) is not Persistence.DURABLE:
        return None
    return OWNER_RECORDS.get(name, (ROUTED_CATEGORY, value))


def assert_complete(member_names: Iterable[str]) -> None:
    """Raise unless every member is declared or grandfathered and every table names only members.

    Reads ``DECLARATIONS``, ``GRANDFATHERED`` and ``OWNER_RECORDS`` when called.
    Each kind of problem is listed with its names sorted and a remedy line.
    """
    members = set(member_names)
    declared = set(DECLARATIONS)
    checks = (
        ("undeclared (neither in DECLARATIONS nor in GRANDFATHERED)", members - declared - GRANDFATHERED,
         "declare each in DECLARATIONS; a new member is never added to GRANDFATHERED"),
        ("in both DECLARATIONS and GRANDFATHERED", declared & GRANDFATHERED,
         "remove each from GRANDFATHERED: the snapshot only shrinks"),
        ("stale in DECLARATIONS (not an EventType member)", declared - members,
         "remove each from DECLARATIONS"),
        ("stale in GRANDFATHERED (not an EventType member)", GRANDFATHERED - members,
         "remove each from GRANDFATHERED"),
        ("stale in OWNER_RECORDS (not an EventType member)", set(OWNER_RECORDS) - members,
         "remove each from OWNER_RECORDS"),
        ("in OWNER_RECORDS but not declared DURABLE",
         {name for name in OWNER_RECORDS if DECLARATIONS.get(name) is not Persistence.DURABLE},
         "declare each DURABLE, or remove it from OWNER_RECORDS"),
    )
    problems = [
        f"- {kind}: {', '.join(sorted(names))}\n  remedy: {remedy}"
        for kind, names, remedy in checks
        if names
    ]
    if problems:
        raise EventPersistenceContractError(
            "AD-1195 event persistence contract (probos/event_persistence.py) is violated:\n"
            + "\n".join(problems)
        )
