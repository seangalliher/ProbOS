# ── unit: parsing + path safety ────────────────────────────────────────────
def test_parse_files_extracts_blocks() -> None:
    raw = (
        "===FILE: SKILL.md===\nhello body\n"
        "===FILE: scripts/x.py===\nprint(1)\n"
    )
    files = SkillForge._parse_files(raw)
    assert files["SKILL.md"] == "hello body"
    assert files["scripts/x.py"] == "print(1)"


def test_parse_files_strips_outer_code_fence() -> None:
    raw = "```\n===FILE: SKILL.md===\nbody\n```"
    files = SkillForge._parse_files(raw)
    assert "SKILL.md" in files


def test_write_files_rejects_path_traversal(tmp_path) -> None:
    with pytest.raises(ValueError):
        SkillForge._write_files(tmp_path, {"../evil.py": "x"})
    with pytest.raises(ValueError):
        SkillForge._write_files(tmp_path, {"/etc/evil": "x"})
