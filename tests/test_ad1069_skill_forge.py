"""AD-1069: SkillForge — generate → validate → smoke-test → register.

Substrate-honest: a scripted LLM returns canned ``===FILE:`` blocks (a real
docx/xlsx/csv-generating skill), a REAL ``SubprocessSandbox`` runs the generated
script during the smoke-test, and a REAL ``CognitiveSkillCatalog`` registers the
result on disk. The headline test then runs the REGISTERED skill's script and
re-opens the produced ``.docx`` — proving the forge ships working skills, and
tying the AD-1065→1069 chain together (forge → register → run → real artifact).
"""

from __future__ import annotations

import io
from pathlib import Path

import pytest

from probos.cognitive.skill_catalog import CognitiveSkillCatalog
from probos.cognitive.skill_forge import SkillForge
from probos.execution.isolation import ExecutionRequest, SubprocessSandbox


# ── canned LLM output ─────────────────────────────────────────────────────
class _FakeLLMResponse:
    def __init__(self, content: str, error=None) -> None:
        self.content = content
        self.error = error


class _FakeLLM:
    """Returns a fixed completion — stands in for the deep-tier generator."""

    def __init__(self, content: str, error=None) -> None:
        self._content = content
        self._error = error
        self.last_request = None

    async def complete(self, request, **_kwargs):
        self.last_request = request
        return _FakeLLMResponse(self._content, self._error)


def _payload(name: str, script_body: str, *, description: str = "A forged test skill.") -> str:
    return (
        "===FILE: SKILL.md===\n"
        "---\n"
        f"name: {name}\n"
        f"description: {description}\n"
        "metadata:\n"
        '  probos-department: "*"\n'
        '  probos-min-rank: "ensign"\n'
        "  probos-activation: discovery\n"
        "---\n\n"
        f"# {name}\n\n"
        "Run scripts/generate.py to produce a sample. Edit CONFIG to customize.\n\n"
        "===FILE: scripts/generate.py===\n"
        f"{script_body}\n"
    )


_DOCX = (
    "from docx import Document\n"
    'CONFIG = {"title": "Sample Report", "body": "Generated by the ProbOS SkillForge."}\n'
    "doc = Document()\n"
    'doc.add_heading(CONFIG["title"], 0)\n'
    'doc.add_paragraph(CONFIG["body"])\n'
    'doc.save("output.docx")\n'
    'print("wrote output.docx")\n'
)

_XLSX = (
    "from openpyxl import Workbook\n"
    'CONFIG = {"rows": [["name", "score"], ["ezri", 9]]}\n'
    "wb = Workbook()\n"
    "ws = wb.active\n"
    'for row in CONFIG["rows"]:\n'
    "    ws.append(row)\n"
    'wb.save("output.xlsx")\n'
    'print("wrote output.xlsx")\n'
)

_CSV = (
    "import csv\n"
    'CONFIG = {"rows": [["name", "score"], ["ezri", "9"]]}\n'
    'with open("output.csv", "w", newline="", encoding="utf-8") as f:\n'
    '    csv.writer(f).writerows(CONFIG["rows"])\n'
    'print("wrote output.csv")\n'
)


async def _catalog(skills_root: Path) -> CognitiveSkillCatalog:
    skills_root.mkdir(parents=True, exist_ok=True)
    cat = CognitiveSkillCatalog(skills_dir=skills_root)
    await cat.start()
    return cat


# ── headline: forge a docx skill, then run the REGISTERED skill ────────────
async def test_forge_docx_skill_registers_and_runs(tmp_path) -> None:
    cat = await _catalog(tmp_path / "skills")
    forge = SkillForge(llm_client=_FakeLLM(_payload("docx-maker", _DOCX)), catalog=cat)

    result = await forge.forge(
        name="docx-maker",
        description="Create a Word document.",
        task="produce a .docx report",
    )

    assert result.success, result.errors
    assert result.name == "docx-maker"
    assert "output.docx" in result.smoke_artifacts
    # Registered with origin=generated (the machine-forged marker).
    entry = cat.get_entry("docx-maker")
    assert entry is not None
    assert entry.origin == "generated"
    # The skill persisted to config/skills/<name>/scripts/generate.py.
    script = Path(entry.skill_dir) / "scripts" / "generate.py"
    assert script.is_file()

    # Run the REGISTERED skill's script → a real, re-openable .docx artifact.
    from docx import Document

    workdir = tmp_path / "use"
    workdir.mkdir()
    res = await SubprocessSandbox(scratch_root=str(tmp_path)).run(
        ExecutionRequest(
            code=script.read_text(encoding="utf-8"),
            workdir=workdir,
            timeout_seconds=60,
        )
    )
    assert res.success, res.stderr
    out = workdir / "output.docx"
    assert out.is_file()
    assert out.read_bytes()[:2] == b"PK"  # docx is a zip archive
    reopened = Document(io.BytesIO(out.read_bytes()))
    texts = "\n".join(p.text for p in reopened.paragraphs)
    assert "Sample Report" in texts


