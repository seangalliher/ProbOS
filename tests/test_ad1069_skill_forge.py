async def test_forge_rejects_duplicate_name(tmp_path) -> None:
    cat = await _catalog(tmp_path / "skills")
    first = await SkillForge(
        llm_client=_FakeLLM(_payload("dup", _CSV)), catalog=cat,
    ).forge(name="dup", description="", task="")
    assert first.success, first.errors
    # Forging the same name again hits the catalog duplicate guard.
    second = await SkillForge(
        llm_client=_FakeLLM(_payload("dup", _CSV)), catalog=cat,
    ).forge(name="dup", description="", task="")
    assert second.success is False
    assert any(
        "registration" in e.lower() or "exist" in e.lower() for e in second.errors
    )


