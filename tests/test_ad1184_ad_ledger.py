"""The reconciled AD/BF ledger must not drift, and its gate must not need a network.

``docs/development/open-ads-report.md`` is generated by
``scripts/gen_ad_ledger.py`` from four authorities. Two of them -- git history
and GitHub issues -- are captured into a pinned snapshot; the other two are
re-parsed on every run. This module is the forcing function: edit DECISIONS.md
or PROGRESS.md without regenerating and the suite goes red.

Fix a failure with::

    python scripts/gen_ad_ledger.py            # refresh the git layer
    python scripts/gen_ad_ledger.py --online   # ...and the issue layer

The load-bearing test here is ``test_check_opens_no_socket_and_spawns_no_process``.
The whole point of the generator is an authority that lives behind a network
call, and a gate that reaches for it would go red on a fork, offline, without a
token, or under rate limiting -- red for a reason unrelated to the code. So the
hermeticity is asserted rather than assumed.
"""

from __future__ import annotations

import importlib.util
import json
import re
import shutil
import socket
import subprocess
import sys
import types
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parent.parent
_SCRIPT = _REPO_ROOT / "scripts" / "gen_ad_ledger.py"
_REPORT = _REPO_ROOT / "docs" / "development" / "open-ads-report.md"
_SNAPSHOT = _REPO_ROOT / "docs" / "development" / "ad-ledger-snapshot.json"


@pytest.fixture(scope="module")
def ledger() -> types.ModuleType:
    """Import the generator from its path -- ``scripts/`` is not a package."""
    spec = importlib.util.spec_from_file_location("gen_ad_ledger", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _section(text: str, heading_prefix: str) -> str:
    """Return the body of the first ``## <heading_prefix>...`` section."""
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if line.startswith("## ") and line[3:].startswith(heading_prefix):
            end = index + 1
            while end < len(lines) and not lines[end].startswith("## "):
                end += 1
            return "\n".join(lines[index:end])
    raise AssertionError(f"no section starting '## {heading_prefix}' in the report")


