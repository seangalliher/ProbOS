# 6. malformed entries are skipped and counted, not fatal
# --------------------------------------------------------------------------


def test_malformed_entries_are_skipped_and_counted(ledger: types.ModuleType) -> None:
    """One bad line must not abort a run over five eras of formatting.

    ``| AD | Decision |`` is a real markdown table header in
    ``progress-era-3-product.md``; it looks like an entry head and is not one.
    """
    found, skipped = ledger.parse_entry_lines(
        [
            "AD-9001 CLOSED. a well-formed entry",
            "AD- : no number at all",
            "BF-: also broken",
            "| AD | Decision |",
            "BF-9002 OPEN. another good one",
        ],
        source="synthetic.md",
        headings_only=False,
    )

    assert "AD-9001" in found and "BF-9002" in found
    assert len(skipped) == 3
    assert all("synthetic.md:" in entry for entry in skipped)


def test_the_real_authorities_report_their_skips(ledger: types.ModuleType) -> None:
    """Skips are surfaced, not swallowed -- a silent skip is a silent lie."""
    _local, skipped, sources = ledger.parse_local_authorities()
    assert sources, "no authority files were parsed"
    assert isinstance(skipped, list)
    assert "Unparseable lines" in _REPORT.read_text(encoding="utf-8")


# --------------------------------------------------------------------------
# 7. ceilings
# --------------------------------------------------------------------------


def test_derived_ceilings_clear_the_known_floor(ledger: types.ModuleType) -> None:
    """AD-1202 (#1142) and BF-712 (#1143) exist only as issues -- no code.

    A recursive tree scan reports AD-1180 / BF-706. If this assertion fails
    with a *lower* number, the issue layer has been lost and the generator is
    reproducing the defect it exists to prevent.
    """
    snapshot = json.loads(_SNAPSHOT.read_text(encoding="utf-8"))
    local, _skipped, _sources = ledger.parse_local_authorities()
    issues = (snapshot.get("issues") or {}).get("issues") or {}
    git_tokens = (snapshot.get("git") or {}).get("tokens") or {}

    ceilings: dict[str, int] = {}
    for key in set(local) | set(issues) | set(git_tokens):
        series, _, digits = key.partition("-")
        ceilings[series] = max(ceilings.get(series, 0), int(digits))

    assert ceilings["AD"] >= 1202, f"AD ceiling regressed to {ceilings['AD']}"
    assert ceilings["BF"] >= 712, f"BF ceiling regressed to {ceilings['BF']}"

    published = _section(_REPORT.read_text(encoding="utf-8"), "Ceilings")
    # Parse the numbers rather than matching a prefix.
    #
    # This read `"**AD-1202**" in published or "**AD-12" in published` and
    # `"**BF-712**" ... or "**BF-7"`, which silently encoded "BF is in the
    # 700s". The docstring says this must fail on a LOWER number; the prefix
    # form failed on a HIGHER one instead. It went red the moment the ceiling
    # reached BF-833 -- growth, which is the opposite of the regression it
    # exists to catch, and it would have taken the AD series with it at
    # AD-1300. Updated rather than deleted, so the change is recorded where
    # the old shape was.
    for series, floor in (("AD", 1202), ("BF", 712)):
        found = [int(n) for n in re.findall(rf"\*\*{series}-(\d+)\*\*", published)]
        assert found, f"the published Ceilings section names no {series} number"
        assert max(found) >= floor, (
            f"published {series} ceiling regressed to {max(found)}"
        )


