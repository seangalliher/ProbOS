"""The reconciled AD/BF ledger must not drift, and its gate must not need a network.

``docs/development/open-ads-report.md`` is generated by
``scripts/gen_ad_ledger.py`` from four authorities. Two of them -- git history
and GitHub issues -- are captured into a pinned snapshot; the other two are
re-parsed on every run. This module is the forcing function: edit DECISIONS.md
or PROGRESS.md without regenerating and the suite goes red.

Fix a failure with::

    python scripts/gen_ad_ledger.py            # refresh the git layer
    python scripts/gen_ad_ledger.py --online   # ...and the issue layer

The load-bearing test here is ``test_check_opens_no_socket_and_spawns_no_process``.
The whole point of the generator is an authority that lives behind a network
call, and a gate that reaches for it would go red on a fork, offline, without a
token, or under rate limiting -- red for a reason unrelated to the code. So the
hermeticity is asserted rather than assumed.
"""

from __future__ import annotations

import importlib.util
import json
