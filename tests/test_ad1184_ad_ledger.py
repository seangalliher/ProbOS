# --------------------------------------------------------------------------
# 2. --check fails on a stale artifact
# --------------------------------------------------------------------------


def test_check_fails_when_the_report_is_stale(
    ledger: types.ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys
) -> None:
    """A mutated copy must be rejected -- otherwise the gate is decorative.

    The unmutated copy is checked first. Without that control a bug in this
    harness would look identical to a working gate.
    """
    report = tmp_path / "open-ads-report.md"
    snapshot = tmp_path / "ad-ledger-snapshot.json"
    shutil.copyfile(_REPORT, report)
    shutil.copyfile(_SNAPSHOT, snapshot)
    monkeypatch.setattr(ledger, "_OUTPUT", report)
    monkeypatch.setattr(ledger, "_SNAPSHOT", snapshot)

    assert ledger.main(["--check"]) == 0, "the unmutated copy should pass"

    report.write_text(
        report.read_text(encoding="utf-8").replace("AD-1202", "AD-1099", 1),
        encoding="utf-8",
    )
    assert ledger.main(["--check"]) == 1
    assert "STALE" in capsys.readouterr().err


def test_check_fails_when_the_report_is_absent(
    ledger: types.ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys
) -> None:
    monkeypatch.setattr(ledger, "_OUTPUT", tmp_path / "nope.md")
    monkeypatch.setattr(ledger, "_SNAPSHOT", tmp_path / "nope.json")
    assert ledger.main(["--check"]) == 1
    assert "MISSING" in capsys.readouterr().err


# --------------------------------------------------------------------------
# 3. --check touches no network and no subprocess
# --------------------------------------------------------------------------


def test_check_opens_no_socket_and_spawns_no_process(
    ledger: types.ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Asserted, not assumed -- this is the constraint the design turns on.

    Both are booby-trapped: a socket because the GitHub authority is a network
    call, and a subprocess because ``gh`` and ``git`` are how it would be
    reached. ``--check`` must resolve the pinned snapshot from disk instead.
    """
    reached: list[str] = []

    def _trap(name: str):
        def _fail(*_args: object, **_kwargs: object):
            reached.append(name)
            raise AssertionError(f"--check reached {name}; it must stay offline")

        return _fail

    for attr in ("socket", "create_connection", "getaddrinfo", "gethostbyname"):
        monkeypatch.setattr(socket, attr, _trap(f"socket.{attr}"))
    for attr in ("run", "Popen", "call", "check_output"):
        monkeypatch.setattr(subprocess, attr, _trap(f"subprocess.{attr}"))

    assert ledger.main(["--check"]) == 0
    assert reached == []


def test_check_and_online_are_mutually_exclusive(
    ledger: types.ModuleType, capsys
) -> None:
    """``--check --online`` must not quietly become a networked gate."""
    assert ledger.main(["--check", "--online"]) == 2
    assert "offline by design" in capsys.readouterr().err


